Write-Host ("Build started {0:yyyy.MM.dd HH:mm:ss}" -f (Get-Date))

$scriptRoot = $PSScriptRoot
$repoRoot = [System.IO.Path]::GetFullPath((Join-Path $scriptRoot ".."))
$version = git describe --always --tags --exclude latest
$globalPackages = (dotnet nuget locals global-packages --list) -split ":\s*", 2 | Select-Object -Last 1
$tag = git describe --always --tags "--abbrev=0" --exclude latest
$revision = git describe --always --tags --exclude latest
$text = @"
// This file is generated by update-version.ps1 
 
using System.Reflection;
 
[assembly: AssemblyVersion("$tag")]
[assembly: AssemblyInformationalVersion("$revision")]
"@
$sevenZip = Join-Path $globalPackages "micasetup.tools\2.5.2\build\bin\7z.exe"
$makemicaPath = Join-Path $globalPackages "micasetup.tools\2.5.2\build\makemica.exe"

# Update Git version info in source code
Write-Host ("$tag")
Write-Host ("$revision")
$text | Out-File $PSScriptRoot\..\src\SecondaryClick\GitVersion.cs -Encoding utf8

# Installer build settings
$appProject = Join-Path $repoRoot "src\SecondaryClick\SecondaryClick.csproj"
$installerProject = Join-Path $repoRoot "src\SecondaryClick.Installer\SecondaryClick.Installer.wixproj"

Set-Location $repoRoot

# Build app output (used by both installer heat harvest and portable package)
# Restore with Release configuration so conditional PackageReference entries (for example Costura.Fody) are included.
dotnet restore $appProject -p:Configuration=Release
dotnet build $appProject -c Release --no-restore

# Build MSI installer (x86_x64)
$vsWhereCmd = Get-Command vswhere.exe -ErrorAction SilentlyContinue
if (-not $vsWhereCmd) {
    throw "vswhere.exe not found in PATH. Please install Visual Studio/Build Tools and ensure vswhere is available."
}

$msbuildExe = & $vsWhereCmd.Source -latest -products * -requires Microsoft.Component.MSBuild -find "MSBuild\**\Bin\MSBuild.exe" | Select-Object -First 1
if ([string]::IsNullOrWhiteSpace($msbuildExe) -or (-not (Test-Path $msbuildExe))) {
    throw "MSBuild.exe not found via vswhere. Please install Visual Studio Build Tools with MSBuild component."
}

if ([string]::IsNullOrWhiteSpace($env:WIX)) {
    throw "WIX environment variable is not set. This project's PreBuildEvent uses $(WIX)bin\heat."
}

####################################################
# app x86_x64 building
####################################################

& $msbuildExe $installerProject /t:Build /p:Configuration=Release /p:Platform=x86 /nologo
if ($LASTEXITCODE -ne 0) {
    throw "Installer build failed: ${installerProject}"
}

# Rename MSI to include git version
$msiPath = Join-Path $scriptRoot "SecondaryClick.msi"
if (Test-Path $msiPath) {
    Remove-Item "${scriptRoot}\SecondaryClick-${version}-x86_x64.msi" -ErrorAction SilentlyContinue
}
Rename-Item $msiPath "SecondaryClick-${version}-x86_x64.msi" -ErrorAction SilentlyContinue

# Build ZIP and 7Zip packages
if (-not (Test-Path $sevenZip)) {
    throw "7z.exe file not found: ${sevenZip}"
}
if (-not (Test-Path $makemicaPath)) {
    throw "makemica.exe file not found: ${makemicaPath}"
}

Set-Location $scriptRoot
$releaseDir = Join-Path $scriptRoot "Release"

if (-not (Test-Path $releaseDir)) {
    throw "Release output folder not found: ${releaseDir}"
}

Remove-Item .\Package.7z -ErrorAction SilentlyContinue
& $sevenZip a Package.7z "${releaseDir}\*" -t7z -mx=9 -ms=on -m0=lzma2 -mf=BCJ2 -r -y

# Build EXE installer by MicaSetup
& $makemicaPath micasetup.json

Remove-Item "SecondaryClick-${version}-x86_x64.zip" -ErrorAction SilentlyContinue
Compress-Archive "${releaseDir}\*" "SecondaryClick-${version}-x86_x64.zip"
Rename-Item .\SecondaryClick.exe "SecondaryClick-${version}-x86_x64.exe" -ErrorAction SilentlyContinue
Rename-Item .\Package.7z "SecondaryClick-${version}-x86_x64.7z" -ErrorAction SilentlyContinue

####################################################
# app arm64 building
####################################################

# Build app output (used by both installer heat harvest and portable package)
# Restore with Release configuration so conditional PackageReference entries (for example Costura.Fody) are included.
dotnet restore $appProject -p:Configuration=Release -p:Platform=arm64
dotnet build $appProject -c Release --no-restore -p:Platform=arm64

# Build ZIP and 7Zip packages
Set-Location $scriptRoot
$releaseDir = Join-Path $scriptRoot "Release"

if (-not (Test-Path $releaseDir)) {
    throw "Release output folder not found: ${releaseDir}"
}

Remove-Item .\Package.7z -ErrorAction SilentlyContinue
& $sevenZip a Package.7z "${releaseDir}\*" -t7z -mx=9 -ms=on -m0=lzma2 -mf=BCJ2 -r -y

# Build EXE installer by MicaSetup
& $makemicaPath micasetup.json

Remove-Item "SecondaryClick-${version}-arm64.zip" -ErrorAction SilentlyContinue
Compress-Archive "${releaseDir}\*" "SecondaryClick-${version}-arm64.zip"
Rename-Item .\SecondaryClick.exe "SecondaryClick-${version}-arm64.exe" -ErrorAction SilentlyContinue
Rename-Item .\Package.7z "SecondaryClick-${version}-arm64.7z" -ErrorAction SilentlyContinue

####################################################
# nuget building
####################################################

$projects = @(
    "..\src\SecondaryClick.MouseKeyHook",
    "..\src\SecondaryClick.WindowsInput"
)

foreach ($proj in $projects) {
    Push-Location $proj
    Write-Host "Processing $proj..."
    dotnet restore
    dotnet build -c Release
    dotnet pack -c Release -o ../../build/
    Pop-Location
}

